import React from 'react';
import { Cpu, Terminal, AlertTriangle } from 'lucide-react';
import { motion } from 'framer-motion';

const ExplanationPanel = ({ explanation }) => {
  // Simple markdown-lite formatter
  const formatText = (text) => {
    return text.split('\n').map((line, i) => {
      if (line.startsWith('### ')) return <h3 key={i} className="text-xl font-bold mt-6 mb-4 text-primary">{line.replace('### ', '')}</h3>;
      if (line.startsWith('#### ')) return <h4 key={i} className="text-lg font-bold mt-4 mb-2 text-white/80">{line.replace('#### ', '')}</h4>;
      if (line.startsWith('**')) {
        const parts = line.split('**');
        return <p key={i} className="mb-2"><span className="font-bold text-primary">{parts[1]}</span>{parts[2]}</p>;
      }
      if (line.startsWith('- ')) return <li key={i} className="ml-4 mb-2 text-white/70 list-disc">{line.replace('- ', '')}</li>;
      return <p key={i} className="mb-2 text-white/70 leading-relaxed">{line}</p>;
    });
  };

  return (
    <motion.div 
      initial={{ opacity: 0, x: 20 }}
      animate={{ opacity: 1, x: 0 }}
      className="glass-card overflow-hidden"
    >
      <div className="p-6 border-b border-white/5 bg-white/5 flex items-center justify-between">
        <div className="flex items-center gap-3">
          <Cpu className="text-accent w-5 h-5" />
          <h3 className="text-lg font-bold">AI Reasoning Engine</h3>
        </div>
        <div className="flex items-center gap-2">
          <div className="w-2 h-2 rounded-full bg-accent animate-pulse" />
          <span className="text-[10px] uppercase font-mono text-white/40">Neural Analysis Active</span>
        </div>
      </div>
      
      <div className="p-8 font-sans max-h-[600px] overflow-y-auto custom-scrollbar">
        {formatText(explanation)}
      </div>
      
      <div className="p-4 bg-background/50 border-t border-white/5 flex items-center gap-4">
        <Terminal className="w-4 h-4 text-white/30" />
        <div className="text-[10px] font-mono text-white/20 uppercase tracking-widest">
          Trace ID: PS-{Math.random().toString(36).substr(2, 9).toUpperCase()} • Generated by LLM Logic Layer
        </div>
      </div>
    </motion.div>
  );
};

export default ExplanationPanel;
